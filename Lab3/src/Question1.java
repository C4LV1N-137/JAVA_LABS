public class Question1 {
    public static void main(String[] args) {
        int count = 10;

        // Count down from 10 to 1 and print each number
        while (count >= 1) {
            System.out.println(count);
            count--;
        }

        // Print "Liftoff!" after the countdown
        System.out.println("Liftoff!");
    }
}