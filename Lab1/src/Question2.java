public class Question2 {
    
    public static void main(String[] args) {
        //One variable of each of 8 primitive data types

        byte byteVal = 100;
        short shortVal = 20000;
        int intVal = 100000;
        long longVal = 10000000000L; //L because value is too large for int
        float floatVal = 3.14f; //f because value is a float
        double doubleVal = 3.14159;
        char charVal = 'C';
        boolean booleanVal = true;

        //Print each variable labelled with its data type name
        System.out.println("Byte: " + byteVal);
        System.out.println("Short: " + shortVal);
        System.out.println("Int: " + intVal);
        System.out.println("Long: " + longVal);
        System.out.println("Float: " + floatVal);
        System.out.println("Double: " + doubleVal);
        System.out.println("Char: " + charVal);
        System.out.println("Boolean: " + booleanVal);

    
    }
}
